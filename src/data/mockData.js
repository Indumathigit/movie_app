// Seat Layout Generator
export function generateSeats(showtimeId) {
  var rows = ["A", "B", "C", "D", "E", "F", "G", "H"]
  var seatsPerRow = 12
  var seats = []
var reservedSeats = ["A3", "A4", "B7", "C2", "C3"]
  for (var i = 0; i < rows.length; i++) {
    var row = rows[i]
    for (var j = 1; j <= seatsPerRow; j++) {
      var seatId = row + j
      var type = "standard"
      if (i <= 1) type = "recliner"
      else if (i >= 2 && i <= 4) type = "premium"

      seats.push({
        id: seatId,
        row: row,
        number: j,
        type: type,
        status: reservedSeats.includes(seatId) ? "reserved" : "available"
      })
    }
  }
  return seats
}

