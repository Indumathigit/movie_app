// Helper: get movie by id
export function getMovieById(id) {
  return movies.find(function(m) { return m.id === id }) || null
}

// Helper: get showtimes by movie id and date
export function getShowtimesByMovie(movieId, date) {
  return showtimes.filter(function(s) {
    return s.movieId === movieId && s.date === date
  })
}

// Helper: get theater by id
export function getTheaterById(id) {
  return theaters.find(function(t) { return t.id === id }) || null
}

// Helper: format duration
export function formatDuration(minutes) {
  var h = Math.floor(minutes / 60)
  var m = minutes % 60
  return h + "h " + m + "m"
}